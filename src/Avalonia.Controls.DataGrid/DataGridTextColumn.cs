    /// <summary>
    /// Represents a <see cref="T:Avalonia.Controls.DataGrid" /> column that hosts textual content in its cells.
    /// </summary>
#if !DATAGRID_INTERNAL
public
#else
internal
#endif
    class DataGridTextColumn : DataGridBoundColumn,
        IDataGridDrawnCellValueProvider,
        IDataGridDrawnCellValueChangeTracking
    {
        private readonly Lazy<ControlTheme> _cellTextBoxTheme;
        private readonly Lazy<ControlTheme> _cellTextBlockTheme;
        private readonly Lazy<ControlTheme> _directTextCellTheme;
        private readonly Lazy<ControlTheme> _drawingCellTheme;

        /// <summary>
        /// Gets the theme applied to editing <see cref="TextBox" /> instances generated by the column.
        /// May return null when no matching resource is found.
        /// </summary>
        protected ControlTheme CellTextBoxTheme => GetThemeValue(_cellTextBoxTheme);

        /// <summary>
        /// Gets the theme applied to display <see cref="TextBlock" /> instances generated by the column.
        /// May return null when no matching resource is found.
        /// </summary>
        protected ControlTheme CellTextBlockTheme => GetThemeValue(_cellTextBlockTheme);

        /// <summary>
        /// Initializes a new instance of the <see cref="T:Avalonia.Controls.DataGridTextColumn" /> class.
        /// </summary>
        public DataGridTextColumn()
        {
            BindingTarget = TextBox.TextProperty;

            _cellTextBoxTheme = new Lazy<ControlTheme>(() => GetColumnControlTheme("DataGridCellTextBoxTheme"));
            _cellTextBlockTheme = new Lazy<ControlTheme>(() => GetColumnControlTheme("DataGridCellTextBlockTheme"));
            _directTextCellTheme = new Lazy<ControlTheme>(() => GetColumnControlTheme("DataGridOptimizedDirectTextCellTheme"));
            _drawingCellTheme = new Lazy<ControlTheme>(() => GetColumnControlTheme("DataGridOptimizedDrawingCellTheme"));
        }

        /// <summary>
        /// Defines the <see cref="UseDirectTextCell"/> property.
        /// </summary>
        public static readonly StyledProperty<bool> UseDirectTextCellProperty =
            AvaloniaProperty.Register<DataGridTextColumn, bool>(nameof(UseDirectTextCell));

        /// <summary>
        /// Gets or sets whether display cells use a retained direct-value text template instead of a nested content presenter.
        /// Editing continues to use the normal retained editor template.
        /// </summary>
        public bool UseDirectTextCell
        {
            get => GetValue(UseDirectTextCellProperty);
            set => SetValue(UseDirectTextCellProperty, value);
        }

        /// <summary>
        /// Defines the <see cref="UseDirectTextContent"/> property.
        /// </summary>
        public static readonly StyledProperty<bool> UseDirectTextContentProperty =
            AvaloniaProperty.Register<DataGridTextColumn, bool>(nameof(UseDirectTextContent));

        /// <summary>
        /// Gets or sets whether an ordinary retained <see cref="DataGridCell"/> and its
        /// template-driven text element read compatible typed accessors directly. This keeps
        /// the normal Avalonia layout/content path while avoiding a binding expression per cell.
        /// </summary>
        public bool UseDirectTextContent
        {
            get => GetValue(UseDirectTextContentProperty);
            set => SetValue(UseDirectTextContentProperty, value);
        }

        /// <summary>
        /// Defines the <see cref="TrackDirectTextValueChanges"/> property.
        /// </summary>
        public static readonly StyledProperty<bool> TrackDirectTextValueChangesProperty =
            AvaloniaProperty.Register<DataGridTextColumn, bool>(nameof(TrackDirectTextValueChanges), true);

        /// <summary>
        /// Gets or sets whether direct retained text cells subscribe to property changes on their
        /// row data and wrapped hierarchy item. Disable this for immutable row data to avoid the
        /// subscription cost; recycled cells still refresh when their data context changes.
        /// </summary>
        public bool TrackDirectTextValueChanges
        {
            get => GetValue(TrackDirectTextValueChangesProperty);
            set => SetValue(TrackDirectTextValueChangesProperty, value);
        }

        internal bool CanUseDirectValueAccessor =>
            BindingCloneHelper.SupportsDirectTextDataContextRead(Binding) &&
            DataGridColumnMetadata.GetValueAccessor(this) is IDataGridColumnTextAccessor;

        internal bool CanUseDirectValueAccessorFor(object item)
        {
            var accessor = DataGridColumnMetadata.GetValueAccessor(this);
            return BindingCloneHelper.SupportsDirectTextDataContextRead(Binding, item is IHierarchicalNodeItem) &&
                   item != null &&
                   accessor != null &&
                   accessor is IDataGridColumnTextAccessor &&
                   accessor.ItemType.IsInstanceOfType(item);
        }

