        s_columnsAutoGenerated?.Add(count);
    }

    public static void RecordSelectionChanged(DataGridSelectionChangeSource source)
    {
        var counter = s_selectionChangedCount;
        if (counter is null)
        {
            return;
        }

        TagList tags = default;
        tags.Add(Tags.SelectionSource, source.ToString());
        counter.Add(1, tags);
    }

    public static void RecordVirtualSurfaceRender(
        int rows,
        int cells,
        int clips,
        int verticalGridLines,
        int textLayoutCacheHits,
        int textLayoutCacheMisses,
        int textDrawOperations,
        int textGlyphRuns,
        int expanderDrawOperations,
        int valueCacheHits,
        int valueCacheMisses)
    {
        Record(s_virtualSurfaceRenderedRows, rows);
        Record(s_virtualSurfaceRenderedCells, cells);
        Record(s_virtualSurfaceClips, clips);
        Record(s_virtualSurfaceVerticalGridLines, verticalGridLines);
        Record(s_virtualSurfaceTextLayoutCacheHits, textLayoutCacheHits);
        Record(s_virtualSurfaceTextLayoutCacheMisses, textLayoutCacheMisses);
        Record(s_virtualSurfaceTextDrawOperations, textDrawOperations);
        Record(s_virtualSurfaceTextGlyphRuns, textGlyphRuns);
        Record(s_virtualSurfaceExpanderDrawOperations, expanderDrawOperations);
        Record(s_virtualSurfaceValueCacheHits, valueCacheHits);
        Record(s_virtualSurfaceValueCacheMisses, valueCacheMisses);
    }

    private static HistogramReportDisposable Begin(Histogram<double>? histogram)
        => histogram is not null ? new HistogramReportDisposable(histogram) : default;

    private static void Record(Counter<long>? counter, int count)
    {
        if (count > 0)
        {
            counter?.Add(count);
        }
    }

    internal readonly ref struct HistogramReportDisposable
    {
        private readonly Histogram<double>? _histogram;
        private readonly long _timestamp;

        public HistogramReportDisposable(Histogram<double> histogram)
        {
            _histogram = histogram;
            _timestamp = Stopwatch.GetTimestamp();
        }

        public void Dispose()
        {
            if (_histogram is null || _timestamp == 0)
            {
                return;
            }

            var elapsedMs = (Stopwatch.GetTimestamp() - _timestamp) * 1000.0 / Stopwatch.Frequency;
            _histogram.Record(elapsedMs);
        }
    }
